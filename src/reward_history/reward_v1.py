"""보상 v1 — 성공 척도를 가장 단순하게 옮긴 점수.

왜 이 보상인가 (쉬운 말):
- 성공 척도의 주 목표는 '90일 누적 순이익'이다. 그래서 하루 보상 = 그날 그 고객에게서 생긴 순이익
  (제보 가치 1,500원 − 리워드 지급 300원)으로 정했다. 90일 보상을 더하면 그대로 그 고객의 90일 순이익이 된다.
- 성공 척도의 두 번째 조건(수신거부 5명 이하)은 v1에 일부러 넣지 않았다. 수신거부하면 그 뒤의 이익이
  사라지므로 간접적으로만 반영된다. 이것만으로 충분한지는 3회차 결과 진단에서 본다.
- 크기 맞추기: 원 단위 그대로면 학습이 불안정하므로 1,000원 = 1점으로 나눈다 (하루 최대 1.5점).
  나누는 값은 성공 척도 계산에는 영향이 없다.
"""

VERSION = "v1"
REWARD_SCALE = 1000.0   # 1,000원 = 1점


def compute_reward(info: dict) -> float:
    return info["profit"] / REWARD_SCALE
